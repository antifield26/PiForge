#!/usr/bin/env node
// Generate the sudoers drop-in that gives the PiForge gateway (piforge-gw) exactly the
// unit/action pairs listed in config/services.allowlist.json.
//
//   node scripts/gen-sudoers.mjs [path/to/services.allowlist.json] > /etc/sudoers.d/piforge-gw
//   node scripts/gen-sudoers.mjs --out /tmp/piforge-gw.sudoers [path/to/services.allowlist.json]
//
// scripts/deploy-pi.sh runs this, validates the output with `visudo -c` and only then
// installs it as /etc/sudoers.d/piforge-gw (mode 0440, root:root).
//
// Only mutating actions become sudoers entries. The gateway calls
// `systemctl is-active <unit>` directly (no sudo) for status and
// `sudo systemctl <action> <unit>` for mutations, so "status" needs no sudo rule.
import { readFileSync, writeFileSync } from "node:fs"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const ALIAS = "PIFORGE_SERVICES"
const GATEWAY_USER = "piforge-gw"
const SYSTEMCTL = "/usr/bin/systemctl"
// Order is the order the verbs appear in the generated file.
const MUTATIONS = ["start", "stop", "restart"]
const KNOWN_ACTIONS = new Set([...MUTATIONS, "status"])
// Conservative systemd unit name charset. Anything else (space, comma, '!', '*', ':', '\')
// would be parsed as sudoers syntax, so refuse to generate instead of quoting it.
const UNIT_RE = /^[A-Za-z0-9@._-]+$/

function fail(message) {
  process.stderr.write(`gen-sudoers: ${message}\n`)
  process.exit(1)
}

const here = dirname(fileURLToPath(import.meta.url))
// Strip `--out <path>` first and treat everything left as a positional argument. The previous
// index-filter version dropped argv[0] whenever --out was absent (index !== -1 && index !== 0
// with outIndex === -1), so an allowlist path was silently ignored and the repository default
// was used instead — a "consistent with the Pi" check could then pass against the wrong file.
const args = process.argv.slice(2)
let outPath = null
const positional = []
for (let index = 0; index < args.length; index++) {
  const arg = args[index]
  if (arg === "--out") {
    const value = args[++index]
    if (!value) fail("--out needs a path")
    if (outPath !== null) fail("--out given twice")
    outPath = value
    continue
  }
  if (arg.startsWith("--")) fail(`unknown option ${JSON.stringify(arg)} (supported: --out <path>)`)
  positional.push(arg)
}
if (positional.length > 1) fail(`expected at most one allowlist path, got ${positional.length}: ${positional.join(", ")}`)
const DEFAULT_ALLOWLIST = resolve(here, "..", "config", "services.allowlist.json")
const allowlistPath = positional[0] ? resolve(positional[0]) : DEFAULT_ALLOWLIST
if (positional.length === 0) {
  // Loud on stderr (stdout may be redirected into a sudoers file) so a caller that meant to
  // pass the Pi's /etc/piforge/services.allowlist.json notices it is reading the repo copy.
  process.stderr.write(`gen-sudoers: using default allowlist: ${allowlistPath}\n`)
}

let parsed
try {
  parsed = JSON.parse(readFileSync(allowlistPath, "utf8"))
} catch (error) {
  fail(`cannot read allowlist ${allowlistPath}: ${error instanceof Error ? error.message : String(error)}`)
}

if (parsed === null || typeof parsed !== "object" || !Array.isArray(parsed.units)) {
  fail(`${allowlistPath}: expected an object with a "units" array`)
}
if (parsed.units.length === 0) {
  fail(`${allowlistPath}: "units" is empty`)
}

const entries = []
for (const unit of parsed.units) {
  if (unit === null || typeof unit !== "object") fail(`${allowlistPath}: unit entries must be objects`)
  const name = unit.name
  if (typeof name !== "string" || !UNIT_RE.test(name)) {
    fail(`${allowlistPath}: refusing unit name ${JSON.stringify(name)} (allowed characters: A-Za-z0-9@._-)`)
  }
  if (!Array.isArray(unit.allow)) fail(`${allowlistPath}: unit ${name} has no "allow" array`)
  for (const action of unit.allow) {
    if (typeof action !== "string" || !KNOWN_ACTIONS.has(action)) {
      fail(`${allowlistPath}: unit ${name} lists unknown action ${JSON.stringify(action)}`)
    }
  }
  for (const action of MUTATIONS) {
    if (unit.allow.includes(action)) entries.push(`${SYSTEMCTL} ${action} ${name}`)
  }
}

if (entries.length === 0) {
  fail(`${allowlistPath}: no start/stop/restart actions to allow — refusing to emit an empty Cmnd_Alias`)
}

const first = `Cmnd_Alias ${ALIAS} = ${entries[0]}`
const rest = entries.slice(1).map((entry) => `    ${entry}`)
const alias = [first, ...rest].join(", \\\n")

const body = [
  "#",
  "# /etc/sudoers.d/piforge-gw",
  "#",
  "# GENERATED FILE — DO NOT EDIT BY HAND.",
  "# Generated by scripts/gen-sudoers.mjs (repo: deploy/sudoers.d-piforge-gw) from",
  "# config/services.allowlist.json. Regenerate with:",
  "#",
  "#   node /home/antifield/piforge/scripts/gen-sudoers.mjs --out /tmp/piforge-gw.sudoers",
  "#   sudo visudo -c -f /tmp/piforge-gw.sudoers && sudo install -m 0440 -o root -g root \\",
  "#     /tmp/piforge-gw.sudoers /etc/sudoers.d/piforge-gw",
  "#",
  `# Grants ${GATEWAY_USER} (the wb-gateway.service runtime user, which has no other sudo`,
  "# rights) exactly the mutating systemctl verbs for the allowlisted units:",
  "#",
  "#   systemctl is-active <unit>       — read-only status, no sudo, any unit",
  `#   sudo systemctl <action> <unit>   — only the ${entries.length} pairs below`,
  "#",
  "# wb-gateway.service therefore deliberately leaves NoNewPrivileges unset: sudo is a",
  "# setuid-root binary and would not be executable with that option set.",
  "#",
  "# sudoers is parsed top-down, so the Cmnd_Alias must be defined before it is used.",
  alias,
  "",
  `${GATEWAY_USER} ALL=(root) NOPASSWD: ${ALIAS}`,
  "",
].join("\n")

// Write with an explicit \n: sudoers on Debian dislikes CRLF, and a UTF-8 BOM is a parse error.
if (outPath) {
  writeFileSync(resolve(outPath), body, { encoding: "utf8", mode: 0o644 })
  process.stderr.write(`gen-sudoers: wrote ${resolve(outPath)}\n`)
} else {
  process.stdout.write(body)
}
